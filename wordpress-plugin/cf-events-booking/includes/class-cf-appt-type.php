<?php
/**
 * Types de rendez-vous — CPT cf_appt_type
 *
 * Chaque type (ex. "Constellations de groupe") définit :
 *   • la durée et les instructions
 *   • la disponibilité hebdomadaire
 *   • la capacité par créneau
 *   • les options de planification (préavis min, fenêtre max, buffer…)
 *   • la synchronisation Google Agenda
 *   • les réunions en ligne
 *   • les informations client demandées
 *   • les notifications e-mail
 *
 * Shortcode : [cf_rdv type="constellations-de-groupe"]
 */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

define( 'CFEB_APPT_SLUG', 'cf_appt_type' );

class CF_ApptType {

	/* ══════════════════════════════════════════════════════════════
	   INIT
	══════════════════════════════════════════════════════════════ */
	public static function init() {
		self::register_cpt();
		add_action( 'add_meta_boxes',         [ __CLASS__, 'register_meta_boxes' ] );
		add_action( 'save_post_' . CFEB_APPT_SLUG, [ __CLASS__, 'save_meta' ], 10, 2 );
		self::register_shortcode();
		add_filter( 'query_vars',             [ __CLASS__, 'register_query_var' ] );
		add_action( 'template_redirect',      [ __CLASS__, 'handle_appt_type_url' ] );
	}

	public static function register_query_var( $vars ) {
		$vars[] = CFEB_APPT_SLUG;
		return $vars;
	}

	/**
	 * Intercepts ?cf_appt_type=slug URLs generated by get_permalink() for this non-public CPT.
	 * Redirects to the configured page_url, or to a page containing [cf_rdv type="slug"],
	 * or renders the widget inline as a fallback.
	 */
	public static function handle_appt_type_url() {
		$slug = get_query_var( CFEB_APPT_SLUG );
		if ( ! $slug ) {
			return;
		}

		$type_post = is_numeric( $slug )
			? get_post( (int) $slug )
			: get_page_by_path( $slug, OBJECT, CFEB_APPT_SLUG );

		if ( ! $type_post || CFEB_APPT_SLUG !== $type_post->post_type ) {
			return;
		}

		$m = self::get_meta( $type_post->ID );

		// 1. Admin-configured page URL takes priority
		if ( ! empty( $m['page_url'] ) ) {
			wp_safe_redirect( $m['page_url'], 302 );
			exit;
		}

		// 2. Search for a page/post containing [cf_rdv type="<slug>"] or [cf_rdv type="<ID>"]
		$search_patterns = [
			'[cf_rdv type="' . $type_post->post_name . '"',
			'[cf_rdv type="' . $type_post->ID . '"',
			"[cf_rdv type='" . $type_post->post_name . "'",
		];
		foreach ( $search_patterns as $pattern ) {
			$pages = get_posts( [
				'post_type'      => [ 'page', 'post' ],
				'post_status'    => 'publish',
				'posts_per_page' => 1,
				's'              => $pattern,
			] );
			if ( ! empty( $pages ) ) {
				wp_safe_redirect( get_permalink( $pages[0]->ID ), 302 );
				exit;
			}
		}

		// 3. Fallback: render the booking widget on a minimal page
		add_filter( 'the_title',   function() use ( $type_post ) { return esc_html( $type_post->post_title ); } );
		add_filter( 'the_content', function() use ( $type_post ) {
			return do_shortcode( '[cf_rdv type="' . $type_post->ID . '"]' );
		} );
		// Let WordPress render the homepage template with our injected content
		add_filter( 'document_title_parts', function( $parts ) use ( $type_post ) {
			$parts['title'] = $type_post->post_title;
			return $parts;
		} );
	}

	/* ══════════════════════════════════════════════════════════════
