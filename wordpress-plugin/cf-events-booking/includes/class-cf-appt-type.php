				'name'          => 'Types de rendez-vous',
				'singular_name' => 'Type de rendez-vous',
				'add_new_item'  => 'Ajouter un type',
				'edit_item'     => 'Modifier le type',
				'all_items'     => 'Tous les types',
				'menu_name'     => '📆 Types RDV',
			],
			'public'              => false,
