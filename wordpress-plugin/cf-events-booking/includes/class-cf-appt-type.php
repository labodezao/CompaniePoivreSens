	/**
	 * Résout le lieu effectif d'une plage horaire : le lieu spécifique choisi
	 * pour cette plage (`lieu_id`) s'il existe encore dans la liste des lieux
	 * enregistrés, sinon le lieu par défaut du type de RDV, sinon l'adresse
	 * par défaut globale (CF Réservations → Paramètres → 📍 Lieux) — pour ne
	 * pas avoir à ressaisir la même adresse sur chaque type de RDV.
	 *
	 * @param array  $m       Retour de self::get_meta()
	 * @param string $lieu_id Peut être vide (= lieu par défaut)
	 * @return array ['nom' => string, 'adresse' => string]
	 */
	private static function resolve_location( array $m, string $lieu_id ): array {
		if ( $lieu_id ) {
			foreach ( $m['locations'] as $loc ) {
				if ( ( $loc['id'] ?? '' ) === $lieu_id ) {
					return [ 'nom' => $loc['nom'] ?? '', 'adresse' => $loc['adresse'] ?? '' ];
				}
			}
		}
		$default = $m['lieu'] ?? '';
		if ( ! $default && class_exists( 'CF_Admin' ) ) {
			$default = CF_Admin::get_options()['default_lieu'] ?? '';
		}
		return [ 'nom' => '', 'adresse' => $default ];
	}

	/**
	 * Extrait, en best-effort, la ville d'une adresse en texte libre
	 * (« 12 rue de la Paix, 75002 Paris » → « Paris »). Utilisé uniquement en
	 * repli quand aucun nom court n'a été donné au lieu (voir « Lieux de
	 * consultation ») : imparfait sur des formats inhabituels, mais on
	 * préfère ne rien afficher plutôt qu'une ville visiblement fausse.
	 */
	private static function extract_city( string $adresse ): string {
		$adresse = trim( $adresse );
		if ( '' === $adresse ) {
			return '';
		}
		if ( str_contains( $adresse, ',' ) ) {
			$adresse = trim( (string) strrchr( $adresse, ',' ), " \t,\n" );
		}
		// Retire un code postal français en tête (« 75002 Paris » → « Paris »).
		$adresse = preg_replace( '/^\d{5}\s+/', '', $adresse );
		return mb_strlen( $adresse ) <= 40 ? $adresse : '';
	}

	/**
	 * Adresse effective d'un créneau déjà réservé, résolue côté serveur (pas
	 * de confiance dans une adresse envoyée par le client) en retrouvant la
	 * plage horaire correspondante parmi les créneaux disponibles de ce jour.
	 *
	 * @param int    $type_id         ID du type de RDV
	 * @param string $slot_debut_full 'YYYY-MM-DDTHH:MM'
	 * @return string
	 */
	public static function resolve_slot_adresse( $type_id, $slot_debut_full ) {
		$date_str = substr( (string) $slot_debut_full, 0, 10 );
		foreach ( self::get_available_slots( $type_id, $date_str ) as $slot ) {
			if ( ( $slot['debut_dt'] ?? '' ) === $slot_debut_full ) {
				return $slot['adresse'] ?? '';
			}
		}
		$m = self::get_meta( $type_id );
		return $m['lieu'] ?? '';
	}

	/**
	 * Fusionne des plages horaires ['debut'=>'HH:MM','fin'=>'HH:MM'] qui se
	 * chevauchent ou coïncident (typiquement : une date spécifique ajoutée le
	 * même jour où la disponibilité hebdomadaire récurrente est déjà active)
	 * en plages disjointes triées chronologiquement. Sans ça, les mêmes
	 * créneaux réservables sont générés deux fois.
	 *
	 * @param array $ranges
	 * @return array
	 */
	private static function merge_ranges( array $ranges ): array {
		if ( count( $ranges ) < 2 ) {
			return $ranges;
		}
		usort( $ranges, static function ( $a, $b ) {
			return strcmp( $a['debut'], $b['debut'] );
		} );
		$merged = [ $ranges[0] ];
		for ( $i = 1, $len = count( $ranges ); $i < $len; $i++ ) {
			$current       = $ranges[ $i ];
			$last          =& $merged[ count( $merged ) - 1 ];
			// Deux plages qui se chevauchent mais avec une modalité ou un lieu
			// différent (ex. 9h-12h présentiel ET 9h-12h distanciel, ou deux
			// lieux différents le même jour) restent distinctes — les fusionner
			// ferait perdre l'une des deux informations.
			$same_modalite = ( $current['modalite'] ?? 'presentiel' ) === ( $last['modalite'] ?? 'presentiel' );
			$same_lieu     = ( $current['lieu_id'] ?? '' ) === ( $last['lieu_id'] ?? '' );
			if ( $same_modalite && $same_lieu && $current['debut'] <= $last['fin'] ) {
				if ( $current['fin'] > $last['fin'] ) {
					$last['fin'] = $current['fin'];
				}
			} else {
				$merged[] = $current;
			}
			unset( $last );
		}
		return $merged;
	}

	/**
	 * Une semaine (identifiée par une date qu'elle contient) est-elle active
	 * pour la disponibilité hebdomadaire récurrente, selon le mode choisi ?
	 * Numéro de semaine ISO-8601 (date('W')) : pas d'ambiguïté, pas besoin de
	 * date de référence pour 'paires'/'impaires'/'semaines'.
	 *
	 * @param string $date_str    Y-m-d
	 * @param array  $recurrence  ['mode','interval','anchor','weeks'] — voir get_meta()
	 */
	public static function week_is_active( string $date_str, array $recurrence ): bool {
		$mode = $recurrence['mode'] ?? 'toutes';
		if ( 'toutes' === $mode || ! $mode ) {
			return true;
		}

		$ts = strtotime( $date_str );
		if ( ! $ts ) {
			return true;
		}
		$iso_week = (int) date( 'W', $ts );

		switch ( $mode ) {
			case 'paires':
				return 0 === ( $iso_week % 2 );
			case 'impaires':
				return 1 === ( $iso_week % 2 );
			case 'semaines':
				return in_array( $iso_week, array_map( 'absint', (array) ( $recurrence['weeks'] ?? [] ) ), true );
			case 'tous_x':
				$interval = max( 2, absint( $recurrence['interval'] ?? 2 ) );
				$anchor   = ! empty( $recurrence['anchor'] ) ? strtotime( $recurrence['anchor'] ) : null;
				if ( ! $anchor ) {
					return true; // pas d'ancre définie : ne bloque rien plutôt que de cacher toute la dispo
				}
				// Semaine (lundi) de la date testée et de l'ancre, pour compter
				// des semaines entières même si l'ancre n'est pas un lundi.
				$week_of = static function ( $timestamp ) {
					$dow = (int) date( 'N', $timestamp );
					return $timestamp - ( $dow - 1 ) * DAY_IN_SECONDS;
				};
				$diff_weeks = (int) round( ( $week_of( $ts ) - $week_of( $anchor ) ) / WEEK_IN_SECONDS );
				return 0 === ( $diff_weeks % $interval );
			default:
				return true;
		}
	}

	/* ══════════════════════════════════════════════════════════════
	   CALCUL DES CRÉNEAUX DISPONIBLES
	══════════════════════════════════════════════════════════════ */
	/**
	 * Retourne les créneaux disponibles pour un type donné à une date donnée.
	 *
	 * @param int    $type_id  ID du type de rendez-vous
	 * @param string $date_str Date YYYY-MM-DD
	 * @return array Liste de ['debut'=>'09:00','fin'=>'10:00','dispo'=>int,'total'=>int]
	 */
	public static function get_available_slots( $type_id, $date_str ) {
		$m       = self::get_meta( $type_id );
		$avail   = $m['availability'];
		$day_num = (int) date( 'N', strtotime( $date_str ) ); // 1=Lun, 7=Dim

		// Plages de la semaine — désactivées si la récurrence choisie exclut
		// cette semaine (ex. "semaines paires"). Les dates spécifiques restent
		// indépendantes de ce filtre, voir plus bas.
		$day_data      = $avail[ $day_num ] ?? null;
		$weekly_ranges = ( $day_data && ! empty( $day_data['enabled'] ) && ! empty( $day_data['slots'] ) && self::week_is_active( $date_str, $m['recurrence'] ) )
			? $day_data['slots']
			: [];

		// Plages issues des dates spécifiques
		$spec_ranges = [];
		foreach ( ( $m['specific_dates'] ?? [] ) as $entry ) {
			if ( isset( $entry['date'] ) && $entry['date'] === $date_str && ! empty( $entry['slots'] ) ) {
				$spec_ranges = $entry['slots'];
				break;
			}
		}

		// Fusion : une date spécifique qui recoupe la disponibilité hebdomadaire
		// du même jour ne doit pas générer les mêmes créneaux deux fois.
		$all_ranges = self::merge_ranges( array_merge( $weekly_ranges, $spec_ranges ) );
		if ( empty( $all_ranges ) ) {
			return [];
		}

		$duree_min = ( 'h' === $m['duree_unit'] ) ? $m['duree'] * 60 : $m['duree'];
		$max_per   = $m['max_places'];
		$buffer_b  = $m['buffer_before'];
		$buffer_a  = $m['buffer_after'];
		$slots     = [];

		$gcal_busy = [];
		if ( class_exists( 'CF_GoogleCalendar' ) && CF_GoogleCalendar::is_connected() ) {
			$gcal_settings  = CF_GoogleCalendar::get_settings();
			$check_calendar = $m['gcal_calendar_id'] ?: $gcal_settings['calendar_id'] ?: 'primary';
			$gcal_busy      = CF_GoogleCalendar::get_busy_times( $date_str, $check_calendar );
		}

		// Fermetures planifiées
		$day_closed = class_exists( 'CF_Planning' ) && CF_Planning::is_closed( $date_str );

		foreach ( $all_ranges as $range ) {
			$ts_debut = strtotime( $date_str . ' ' . $range['debut'] );
			$ts_fin   = strtotime( $date_str . ' ' . $range['fin'] );

			if ( ! $ts_debut || ! $ts_fin || $ts_fin <= $ts_debut ) {
				continue;
			}

			$slot_start = $ts_debut + $buffer_b * 60;
			while ( $slot_start + $duree_min * 60 + $buffer_a * 60 <= $ts_fin ) {
				$slot_end = $slot_start + $duree_min * 60;

				$s_debut_str = date( 'H:i', $slot_start );
				$s_fin_str   = date( 'H:i', $slot_end );
				$s_debut_dt  = $date_str . 'T' . $s_debut_str;

				// Contraintes de planification
				$skip = false;
				// Toujours exclure les créneaux déjà passés
				if ( $slot_start <= time() ) {
					$skip = true;
				}
				if ( ! $skip && $m['delai_min'] > 0 && $slot_start <= time() + $m['delai_min'] * 3600 ) {
					$skip = true;
				}
				if ( $m['max_jours'] > 0 && $slot_start > time() + $m['max_jours'] * DAY_IN_SECONDS ) {
					$skip = true;
				}
				if ( $day_closed ) {
					$skip = true;
				}
				// Vérifier contre les événements Google Agenda
				if ( ! $skip && $gcal_busy && ! CF_GoogleCalendar::slot_is_free( $slot_start, $slot_end, $gcal_busy ) ) {
					$skip = true;
				}

				if ( ! $skip ) {
					$booked = CF_Booking::count_for_slot( $type_id, $s_debut_dt );
					$dispo  = max( 0, $max_per - $booked );
					$loc    = self::resolve_location( $m, $range['lieu_id'] ?? '' );

					$slots[] = [
						'debut'     => $s_debut_str,
						'fin'       => $s_fin_str,
						'debut_dt'  => $s_debut_dt,
						'fin_dt'    => $date_str . 'T' . $s_fin_str,
						'dispo'     => $dispo,
						'total'     => $max_per,
						'complet'   => ( $dispo <= 0 ),
						'modalite'  => $range['modalite'] ?? 'presentiel',
						'adresse'   => $loc['adresse'],
						'lieu_nom'  => $loc['nom'],
					];
				}

				$slot_start += ( $duree_min + $buffer_a ) * 60;
			}
		}

		return $slots;
	}

	/* ── Bouton créneau (partagé grille + liste) ────────────────── */
	private static function slot_button_html( array $slot, int $type_id ): string {
		// Chaque créneau porte son propre type (vues multi-types) ; on privilégie
		// celui-ci pour que la réservation cible le bon type de rendez-vous.
		if ( isset( $slot['type_id'] ) ) {
			$type_id = (int) $slot['type_id'];
		}
		$complet = $slot['complet'];
		$debut_h = str_replace( ':', 'h', $slot['debut'] );
		$fin_h   = str_replace( ':', 'h', substr( $slot['fin_dt'], 11, 5 ) );
		$label   = $debut_h . ' – ' . $fin_h;

		$places_html = '';
		if ( ! $complet && $slot['total'] > 1 ) {
			$dispo = (int) $slot['dispo'];
			if ( $dispo <= 5 ) {
				$places_html = ' <span class="cf-rdv-places">' . $dispo . ' pl. restante' . ( $dispo > 1 ? 's' : '' ) . '</span>';
			}
		}

		$slot_modalite = $slot['modalite'] ?? 'presentiel';
		// Ville du lieu de ce créneau (utile quand plusieurs lieux de
		// consultation sont enregistrés — voir mb_availability()) : le nom
		// court du lieu choisi pour cette plage s'il y en a un, sinon une
		// extraction best-effort depuis l'adresse complète.
		$ville = 'presentiel' === $slot_modalite
			? ( $slot['lieu_nom'] ?: self::extract_city( $slot['adresse'] ?? '' ) )
			: '';

		// La modalité n'est affichée à côté de l'heure que si ce type de RDV
		// propose bien les deux (sinon tous les créneaux ont trivialement la
		// même modalité, l'indiquer partout serait juste du bruit visuel) —
		// sauf la ville, affichée dès qu'elle est connue, y compris pour un
		// type « présentiel uniquement » qui reçoit à plusieurs endroits.
		$modalite_html = '';
		if ( 'les_deux' === self::get_modalite( $type_id ) ) {
			$modalite_html = 'distanciel' === $slot_modalite
				? ' <span class="cf-rdv-modalite cf-rdv-modalite--distanciel">🖥️ Distanciel</span>'
				: ' <span class="cf-rdv-modalite cf-rdv-modalite--presentiel">📍 Présentiel' . ( $ville ? ' · ' . esc_html( $ville ) : '' ) . '</span>';
		} elseif ( $ville ) {
			$modalite_html = ' <span class="cf-rdv-modalite cf-rdv-modalite--presentiel">📍 ' . esc_html( $ville ) . '</span>';
		}

		return sprintf(
			'<button type="button" class="cf-rdv-slot%s" data-debut="%s" data-fin="%s" data-type-id="%d" data-modalite="%s"%s>%s%s%s%s</button>',
			$complet ? ' cf-rdv-slot--full' : '',
			esc_attr( $slot['debut_dt'] ),
			esc_attr( $slot['fin_dt'] ),
			$type_id,
			esc_attr( $slot['modalite'] ?? 'presentiel' ),
			$complet ? ' disabled' : '',
			esc_html( $label ),
			$modalite_html,
			$places_html,
			$complet ? ' <span class="cf-rdv-full-badge">Complet</span>' : ''
		);
	}

	/**
	 * Résout l'attribut `type` (slug, ID numérique, ou une liste séparée par
	 * des virgules / « + » de ceux-ci) en un tableau ordonné et dédupliqué
	 * d'IDs de types de rendez-vous valides.
	 *
	 * Exemples acceptés :
	 *   "constellations-de-groupes"
	 *   "constellations-de-groupes,ateliers-genogrammes"
	 *   "constellations-de-groupes + ateliers-genogrammes"
	 *   "12, 34"
	 *
	 * @param string|int|array $type
	 * @return int[]
	 */
	public static function normalize_type_ids( $type ) {
		$tokens = is_array( $type ) ? $type : preg_split( '/[,+]/', (string) $type );
		$ids    = [];

		foreach ( (array) $tokens as $token ) {
			$token = trim( (string) $token );
			if ( '' === $token ) {
				continue;
			}
			$post = is_numeric( $token )
				? get_post( (int) $token )
				: get_page_by_path( $token, OBJECT, CFEB_APPT_SLUG );

			if ( $post && CFEB_APPT_SLUG === $post->post_type ) {
				// Clé = ID pour dédupliquer tout en préservant l'ordre d'apparition.
				$ids[ (int) $post->ID ] = (int) $post->ID;
			}
		}

		return array_values( $ids );
	}

	/**
	 * Rassemble les créneaux disponibles d'un ou plusieurs types pour une date
	 * donnée, fusionnés et triés chronologiquement. Chaque créneau conserve son
	 * propre `type_id` afin que la réservation cible le bon type.
	 *
	 * @param int[]  $type_ids
	 * @param string $date_str  Y-m-d
	 * @return array
	 */
	public static function collect_slots( array $type_ids, $date_str ) {
		$out = [];
		foreach ( $type_ids as $tid ) {
			foreach ( self::get_available_slots( $tid, $date_str ) as $slot ) {
				$slot['type_id'] = (int) $tid;
				$out[]           = $slot;
			}
		}
		usort( $out, static function ( $a, $b ) {
			return strcmp( $a['debut_dt'], $b['debut_dt'] );
		} );
		return $out;
	}

	/**
	 * Les N prochaines dates à venir (un créneau représentatif par jour, le
	 * plus tôt) pour un ensemble de types de RDV confondus — utilisé pour des
	 * résumés courts (ex. widget « Prochaines dates » de la barre latérale
	 * des articles), pas pour la liste de réservation complète qui affiche
	 * tous les créneaux de chaque jour (voir render_slot_list()).
	 *
	 * @param int[] $type_ids
	 * @param int   $limit
	 * @param int   $max_days Horizon de recherche
	 * @return array [ ['type_id'=>int,'date_str'=>string,'debut_dt'=>string], ... ]
	 */
	public static function get_next_occurrences( array $type_ids, int $limit = 3, int $max_days = 120 ): array {
		$type_ids = array_values( array_filter( array_map( 'absint', $type_ids ) ) );
		if ( empty( $type_ids ) ) {
			return [];
		}
		$today = strtotime( 'today' );
		$out   = [];
		for ( $d = 0; $d < $max_days && count( $out ) < $limit; $d++ ) {
			$date_str = date( 'Y-m-d', strtotime( "+{$d} days", $today ) );
			$slots    = self::collect_slots( $type_ids, $date_str );
			if ( empty( $slots ) ) {
				continue;
			}
			$first = $slots[0];
			$out[] = [
				'type_id'  => (int) ( $first['type_id'] ?? $type_ids[0] ),
				'date_str' => $date_str,
				'debut_dt' => $first['debut_dt'],
			];
		}
		return $out;
	}

	/* ══════════════════════════════════════════════════════════════
	   GRILLE HEBDOMADAIRE — utilisée par shortcode + AJAX
	══════════════════════════════════════════════════════════════ */
	public static function render_week_grid( $type_id, $week_start_str ) {
		$type_ids = self::normalize_type_ids( $type_id );
		if ( empty( $type_ids ) ) {
			return '';
		}
		$type_attr = implode( ',', $type_ids );

		$week_start = strtotime( $week_start_str );
		if ( ! $week_start ) {
			return '';
		}
		$today    = strtotime( 'today' );
		$dow_now  = (int) date( 'N', $today );
		$this_mon = $today - ( $dow_now - 1 ) * DAY_IN_SECONDS;

		$jours = [ 1 => 'Lun', 2 => 'Mar', 3 => 'Mer', 4 => 'Jeu', 5 => 'Ven', 6 => 'Sam', 7 => 'Dim' ];

		/*
		 * Si la semaine demandée est vide, on scanne les semaines suivantes
		 * (jusqu'à ~90 jours) pour atterrir directement sur la prochaine qui a
		 * du contenu — plutôt qu'une grille vide invitant juste à cliquer
		 * « Suivante » à répétition. $week_start est réassigné à la semaine
		 * réellement affichée : la nav (précédente/suivante/libellé) qui suit
		 * est donc toujours cohérente avec ce qui est montré.
		 */
		$max_weeks_ahead = 13; // ≈ 90 jours
		$days_data        = [];
		$visible_count    = 0;
		$found            = false;

		for ( $w = 0; $w <= $max_weeks_ahead; $w++ ) {
			$candidate_start = strtotime( "+{$w} weeks", $week_start );
			$candidate_days  = [];
			for ( $d = 0; $d < 7; $d++ ) {
				$day_ts      = strtotime( "+{$d} days", $candidate_start );
				$date_str    = date( 'Y-m-d', $day_ts );
				$is_past     = ( $day_ts < $today );
				$slots       = $is_past ? [] : self::collect_slots( $type_ids, $date_str );
				$has_slots   = ! empty( $slots );
				$candidate_days[] = [
					'ts'       => $day_ts,
					'date_str' => $date_str,
					'day_num'  => (int) date( 'N', $day_ts ),
					'is_past'  => $is_past,
					'slots'    => $slots,
					'visible'  => $has_slots,
				];
			}
			$candidate_visible = count( array_filter( $candidate_days, fn( $d ) => $d['visible'] ) );
			if ( $candidate_visible > 0 ) {
				$week_start    = $candidate_start;
				$days_data     = $candidate_days;
				$visible_count = $candidate_visible;
				$found         = true;
				break;
			}
		}

		$week_end = strtotime( '+6 days', $week_start );
		$prev_ts  = strtotime( '-7 days', $week_start );
		$next_ts  = strtotime( '+7 days', $week_start );

		// Navigation
		$html  = '<div class="cf-rdv-cal-nav">';
		$html .= sprintf(
			'<button type="button" class="cf-rdv-prev-week" data-type-id="%s" data-week="%s"%s>‹ Précédente</button>',
			esc_attr( $type_attr ),
			esc_attr( date( 'Y-m-d', $prev_ts ) ),
			$prev_ts < $this_mon ? ' disabled' : ''
		);
		$html .= '<span class="cf-rdv-cal-week-label">'
			. esc_html( date_i18n( 'j F', $week_start ) . ' – ' . date_i18n( 'j F Y', $week_end ) )
			. '</span>';
		$html .= sprintf(
			'<button type="button" class="cf-rdv-next-week" data-type-id="%s" data-week="%s">Suivante ›</button>',
			esc_attr( $type_attr ),
			esc_attr( date( 'Y-m-d', $next_ts ) )
		);
		$html .= '</div>';

		if ( ! $found ) {
			// Rien dans la fenêtre scannée : plutôt qu'un cul-de-sac, on
			// propose de recevoir un signal dès qu'un créneau s'ouvre
			// (système newsletter maison, voir modules/newsletter).
			$html .= '<div class="cf-rdv-cal-empty">';
			if ( shortcode_exists( 'cf_newsletter' ) ) {
				$html .= do_shortcode( '[cf_newsletter titre="Sois averti·e dès l\'ouverture de nouveaux créneaux"]' );
			} else {
				$html .= 'Aucun créneau disponible pour le moment.';
			}
			$html .= '</div>';
			return $html;
		}

		$html .= '<div class="cf-rdv-cal-grid" style="grid-template-columns:repeat(' . $visible_count . ',1fr);">';

		foreach ( $days_data as $day ) {
			if ( ! $day['visible'] ) {
				continue;
			}

			$html .= '<div class="cf-rdv-cal-day" data-date="' . esc_attr( $day['date_str'] ) . '">';
			$html .= '<div class="cf-rdv-cal-day-hd">';
			$html .= '<span class="cf-rdv-cal-day-name">' . esc_html( $jours[ $day['day_num'] ] ) . '</span>';
			$html .= '<span class="cf-rdv-cal-day-num">' . esc_html( date_i18n( 'j', $day['ts'] ) ) . '</span>';
			$html .= '</div>';
			$html .= '<div class="cf-rdv-cal-slots">';

			foreach ( $day['slots'] as $slot ) {
				// Chaque créneau porte son propre type_id (voir collect_slots).
				$html .= self::slot_button_html( $slot, 0 );
			}

			$html .= '</div></div>';
		}
		$html .= '</div>';

		return $html;
	}

	/**
	 * Render upcoming available slots as a flat chronological list.
	 * Scans day by day (up to $max_days) until $limit slot-days are collected,
	 * regardless of how far in the future they are.
	 *
	 * @param int         $type_id     Appointment type post ID.
	 * @param string|null $from_date   Y-m-d start date (default: today). Ignored when $before_date is set.
	 * @param int         $limit       Max number of distinct days with slots to show.
	 * @param int         $max_days    Hard ceiling on how many days to scan.
	 * @param string|null $before_date Y-m-d exclusive upper bound — quand fourni, affiche la page
	 *                                 PRÉCÉDENTE (les $limit derniers jours avec créneaux avant cette
	 *                                 date), symétrique du scan avant utilisé pour "Voir plus de dates".
	 */
	public static function render_slot_list( $type_id, $from_date = null, $limit = 8, $max_days = 730, $before_date = null ) {
		$type_ids = self::normalize_type_ids( $type_id );
		if ( empty( $type_ids ) ) {
			return '';
		}
		$type_attr = implode( ',', $type_ids );

		$today     = strtotime( 'today' );
		$prev_from = null; // date à repasser en $before_date pour reculer encore d'une page

		if ( $before_date ) {
			$before_ts = strtotime( $before_date );
			$all_days  = [];
			if ( $before_ts && $before_ts > $today ) {
				for ( $d = 0; $d < $max_days; $d++ ) {
					$day_ts = strtotime( "+{$d} days", $today );
					if ( $day_ts >= $before_ts ) {
						break;
					}
					$date_str = date( 'Y-m-d', $day_ts );
					$slots    = self::collect_slots( $type_ids, $date_str );
					if ( ! empty( $slots ) ) {
						$all_days[ $date_str ] = [ 'ts' => $day_ts, 'slots' => $slots ];
					}
				}
			}
			$total         = count( $all_days );
			$slots_by_date = array_slice( $all_days, max( 0, $total - $limit ), $limit, true );
			// "Suivant" depuis une page reculée reprend exactement là où elle s'arrête.
			$next_from = $before_date;
			if ( $total > $limit ) {
				$prev_from = array_key_first( $slots_by_date );
			}
		} else {
			$from_ts = $from_date ? strtotime( $from_date ) : $today;
			if ( ! $from_ts || $from_ts < $today ) {
				$from_ts = $today;
			}

			$slots_by_date = [];
			$next_from     = null;

			for ( $d = 0; $d < $max_days; $d++ ) {
				if ( count( $slots_by_date ) >= $limit ) {
					$next_from = date( 'Y-m-d', strtotime( "+{$d} days", $from_ts ) );
					break;
				}
				$day_ts   = strtotime( "+{$d} days", $from_ts );
				$date_str = date( 'Y-m-d', $day_ts );
				$slots    = self::collect_slots( $type_ids, $date_str );
				if ( ! empty( $slots ) ) {
					$slots_by_date[ $date_str ] = [ 'ts' => $day_ts, 'slots' => $slots ];
				}
			}

			// Un bouton "précédent" n'a de sens que si on n'est pas déjà sur
			// la toute première page (from_date == aujourd'hui).
			if ( $from_ts > $today && ! empty( $slots_by_date ) ) {
				$prev_from = array_key_first( $slots_by_date );
			}
		}

		$html = '<div class="cf-rdv-list" data-type-id="' . esc_attr( $type_attr ) . '">';

		if ( empty( $slots_by_date ) ) {
			$html .= '<div class="cf-rdv-list-empty">Aucun créneau disponible à venir.</div>';
		} else {
			if ( $prev_from ) {
				$html .= sprintf(
					'<button type="button" class="cf-rdv-list-prev" data-type-id="%s" data-before="%s" data-limit="%d">‹ Dates précédentes</button>',
					esc_attr( $type_attr ),
					esc_attr( $prev_from ),
					(int) $limit
				);
			}

			foreach ( $slots_by_date as $date_str => $data ) {
				$ts   = $data['ts'];
				$html .= '<div class="cf-rdv-list-day">';
				$html .= '<div class="cf-rdv-list-day-hd">' . esc_html( ucfirst( date_i18n( 'l', $ts ) ) . ' ' . date_i18n( 'j F Y', $ts ) ) . '</div>';
				$html .= '<div class="cf-rdv-list-slots">';
				foreach ( $data['slots'] as $slot ) {
					// Chaque créneau porte son propre type_id (voir collect_slots).
					$html .= self::slot_button_html( $slot, 0 );
				}
				$html .= '</div>';
				$html .= '</div>';
			}

			if ( $next_from ) {
				$html .= sprintf(
					'<button type="button" class="cf-rdv-list-more" data-type-id="%s" data-from="%s" data-limit="%d">Voir plus de dates ›</button>',
					esc_attr( $type_attr ),
					esc_attr( $next_from ),
					(int) $limit
				);
			}
		}

		$html .= '</div>';
		return $html;
	}

