	/* ══════════════════════════════════════════════════════════════
	   SAUVEGARDE META
	══════════════════════════════════════════════════════════════ */
	public static function save_meta( $post_id, $post ) {
		if (
			! isset( $_POST['cfeb_appt_nonce'] ) ||
			! wp_verify_nonce( sanitize_text_field( wp_unslash( $_POST['cfeb_appt_nonce'] ) ), 'cfeb_save_appt_type' ) ||
			( defined( 'DOING_AUTOSAVE' ) && DOING_AUTOSAVE ) ||
			! current_user_can( 'edit_post', $post_id )
		) {
			return;
		}

		// ── Bases ──────────────────────────────────────────────
		$duree      = max( 1, absint( $_POST['cfeb_appt_duree']      ?? 60 ) );
		$duree_unit = in_array( $_POST['cfeb_appt_duree_unit'] ?? '', [ 'min', 'h' ], true ) ? $_POST['cfeb_appt_duree_unit'] : 'min';
		$color      = sanitize_hex_color( wp_unslash( $_POST['cfeb_appt_color']     ?? '#2271b1' ) );
		$animateur  = sanitize_text_field( wp_unslash( $_POST['cfeb_appt_animateur'] ?? '' ) );
		$email      = sanitize_email( wp_unslash( $_POST['cfeb_appt_email']          ?? '' ) );
		$prix       = max( 0, (float) ( $_POST['cfeb_appt_prix']                     ?? 0 ) );
		$layout     = in_array( $_POST['cfeb_appt_layout'] ?? '', [ 'hebdomadaire', 'mensuel', 'liste' ], true ) ? $_POST['cfeb_appt_layout'] : 'hebdomadaire';
		$instructions = sanitize_textarea_field( wp_unslash( $_POST['cfeb_appt_instructions'] ?? '' ) );
		$lieu         = sanitize_text_field( wp_unslash( $_POST['cfeb_appt_lieu']              ?? '' ) );
		$categorie    = sanitize_text_field( wp_unslash( $_POST['cfeb_appt_categorie']         ?? '' ) );

		update_post_meta( $post_id, '_cfeb_appt_duree',        $duree );
		update_post_meta( $post_id, '_cfeb_appt_duree_unit',   $duree_unit );
		update_post_meta( $post_id, '_cfeb_appt_color',        $color ?: '#2271b1' );
		update_post_meta( $post_id, '_cfeb_appt_animateur',    $animateur );
		update_post_meta( $post_id, '_cfeb_appt_email',        $email );
		update_post_meta( $post_id, '_cfeb_appt_prix',         $prix );
		update_post_meta( $post_id, '_cfeb_appt_layout',       $layout );
		update_post_meta( $post_id, '_cfeb_appt_instructions', $instructions );
		update_post_meta( $post_id, '_cfeb_appt_lieu',         $lieu );
		update_post_meta( $post_id, '_cfeb_appt_categorie',    $categorie );
		update_post_meta( $post_id, '_cfeb_appt_page_url',     esc_url_raw( wp_unslash( $_POST['cfeb_appt_page_url'] ?? '' ) ) );

		// Lieux valides pour le choix par créneau : liste partagée gérée depuis
		// CF Réservations → Paramètres → 📍 Lieux (pas propre à ce type).
		$valid_lieu_ids = class_exists( 'CF_Admin' ) ? wp_list_pluck( CF_Admin::get_locations(), 'id' ) : [];

		// ── Disponibilité ──────────────────────────────────────
		$avail_raw = isset( $_POST['cfeb_avail'] ) ? (array) $_POST['cfeb_avail'] : [];
		$avail     = [];
		for ( $d = 1; $d <= 7; $d++ ) {
			$day_data = $avail_raw[ $d ] ?? [];
			$enabled  = ! empty( $day_data['enabled'] );
			$slots    = [];
			if ( $enabled && ! empty( $day_data['slots'] ) ) {
				foreach ( (array) $day_data['slots'] as $slot ) {
					$debut    = sanitize_text_field( $slot['debut'] ?? '' );
					$fin      = sanitize_text_field( $slot['fin']   ?? '' );
					$modalite = sanitize_key( $slot['modalite'] ?? 'presentiel' );
					if ( ! in_array( $modalite, [ 'presentiel', 'distanciel' ], true ) ) {
						$modalite = 'presentiel';
					}
					$lieu_id = sanitize_key( $slot['lieu_id'] ?? '' );
					if ( ! in_array( $lieu_id, $valid_lieu_ids, true ) ) {
						$lieu_id = '';
					}
					if ( $debut && $fin && $fin > $debut ) {
						$slots[] = [ 'debut' => $debut, 'fin' => $fin, 'modalite' => $modalite, 'lieu_id' => $lieu_id ];
					}
				}
			}
			$avail[ $d ] = [ 'enabled' => $enabled, 'slots' => $slots ];
		}
		update_post_meta( $post_id, '_cfeb_appt_availability', wp_json_encode( $avail ) );

		// ── Récurrence de la disponibilité hebdomadaire ─────────
		$recur_mode = $_POST['cfeb_appt_recurrence_mode'] ?? 'toutes';
		if ( ! in_array( $recur_mode, [ 'toutes', 'paires', 'impaires', 'tous_x', 'semaines' ], true ) ) {
			$recur_mode = 'toutes';
		}
		$recur_weeks = array_values( array_unique( array_filter( array_map( 'absint', (array) ( $_POST['cfeb_appt_recurrence_weeks'] ?? [] ) ), static function ( $w ) {
			return $w >= 1 && $w <= 53;
		} ) ) );
		sort( $recur_weeks );
		update_post_meta( $post_id, '_cfeb_appt_recurrence', wp_json_encode( [
			'mode'     => $recur_mode,
			'interval' => max( 2, min( 12, absint( $_POST['cfeb_appt_recurrence_interval'] ?? 2 ) ) ),
			'anchor'   => sanitize_text_field( wp_unslash( $_POST['cfeb_appt_recurrence_anchor'] ?? '' ) ),
			'weeks'    => $recur_weeks,
		] ) );

		// ── Capacité ───────────────────────────────────────────
		update_post_meta( $post_id, '_cfeb_appt_max_places',  absint( $_POST['cfeb_appt_max_places']  ?? 1 ) );
		update_post_meta( $post_id, '_cfeb_appt_daily_limit', absint( $_POST['cfeb_appt_daily_limit'] ?? 0 ) );

		// ── Planification ──────────────────────────────────────
		update_post_meta( $post_id, '_cfeb_appt_delai_min',     absint( $_POST['cfeb_appt_delai_min']     ?? 0 ) );
		update_post_meta( $post_id, '_cfeb_appt_max_jours',     absint( $_POST['cfeb_appt_max_jours']     ?? 0 ) );
		update_post_meta( $post_id, '_cfeb_appt_buffer_before', absint( $_POST['cfeb_appt_buffer_before'] ?? 0 ) );
		update_post_meta( $post_id, '_cfeb_appt_buffer_after',  absint( $_POST['cfeb_appt_buffer_after']  ?? 0 ) );
		update_post_meta( $post_id, '_cfeb_appt_cancel_limit',  absint( $_POST['cfeb_appt_cancel_limit']  ?? 0 ) );
		update_post_meta( $post_id, '_cfeb_appt_liste_attente', ! empty( $_POST['cfeb_appt_liste_attente'] ) ? 1 : 0 );

		// ── Google Agenda ──────────────────────────────────────
		update_post_meta( $post_id, '_cfeb_appt_gcal_enabled',         ! empty( $_POST['cfeb_appt_gcal_enabled'] ) ? 1 : 0 );
		update_post_meta( $post_id, '_cfeb_appt_gcal_calendar_id',     sanitize_text_field( wp_unslash( $_POST['cfeb_appt_gcal_calendar_id']     ?? '' ) ) );
		update_post_meta( $post_id, '_cfeb_appt_gcal_title_template',  sanitize_text_field( wp_unslash( $_POST['cfeb_appt_gcal_title_template']  ?? '' ) ) );

		// ── Réunion en ligne ───────────────────────────────────
		$platform = sanitize_text_field( wp_unslash( $_POST['cfeb_appt_online_platform'] ?? '' ) );
		if ( ! in_array( $platform, [ '', 'zoom', 'meet', 'teams', 'jitsi', 'autre' ], true ) ) {
			$platform = '';
		}
		update_post_meta( $post_id, '_cfeb_appt_online_platform', $platform );
		update_post_meta( $post_id, '_cfeb_appt_online_url',      esc_url_raw( wp_unslash( $_POST['cfeb_appt_online_url'] ?? '' ) ) );

		$room_mode = sanitize_key( wp_unslash( $_POST['cfeb_appt_online_room_mode'] ?? '' ) );
		if ( ! in_array( $room_mode, [ 'creneau', 'fixe' ], true ) ) {
			$room_mode = 'creneau';
		}
		update_post_meta( $post_id, '_cfeb_appt_online_room_mode', $room_mode );
		update_post_meta( $post_id, '_cfeb_appt_online_code',      sanitize_text_field( wp_unslash( $_POST['cfeb_appt_online_code'] ?? '' ) ) );

		$modalite = sanitize_key( wp_unslash( $_POST['cfeb_appt_modalite'] ?? '' ) );
		if ( ! in_array( $modalite, [ 'presentiel', 'distanciel', 'les_deux' ], true ) ) {
			$modalite = $platform ? 'distanciel' : 'presentiel';
		}
		update_post_meta( $post_id, '_cfeb_appt_modalite', $modalite );

		// ── Informations client ────────────────────────────────
		update_post_meta( $post_id, '_cfeb_appt_require_phone',   ! empty( $_POST['cfeb_appt_require_phone'] )   ? 1 : 0 );
		update_post_meta( $post_id, '_cfeb_appt_require_address', ! empty( $_POST['cfeb_appt_require_address'] ) ? 1 : 0 );
		$cf_raw = sanitize_textarea_field( wp_unslash( $_POST['cfeb_appt_custom_fields'] ?? '' ) );
		if ( $cf_raw ) {
			$cf_decoded = json_decode( $cf_raw, true );
			update_post_meta( $post_id, '_cfeb_appt_custom_fields', is_array( $cf_decoded ) ? wp_json_encode( $cf_decoded ) : '' );
		} else {
			update_post_meta( $post_id, '_cfeb_appt_custom_fields', '' );
		}

		// ── Notifications ──────────────────────────────────────
		update_post_meta( $post_id, '_cfeb_appt_notif_confirm',  ! empty( $_POST['cfeb_appt_notif_confirm'] )  ? 1 : 0 );
		update_post_meta( $post_id, '_cfeb_appt_notif_admin',    ! empty( $_POST['cfeb_appt_notif_admin'] )    ? 1 : 0 );
		update_post_meta( $post_id, '_cfeb_appt_reminder_hours', absint( $_POST['cfeb_appt_reminder_hours']   ?? 0 ) );
		update_post_meta( $post_id, '_cfeb_appt_followup_hours', absint( $_POST['cfeb_appt_followup_hours']   ?? 0 ) );
		// wp_kses_post (pas sanitize_textarea_field, qui retire tout le HTML) :
		// ce message est saisi via l'éditeur WYSIWYG de cette page (accès déjà
		// filtré par le current_user_can('edit_post') ci-dessus) — le HTML
		// qu'il contient doit être conservé pour être ensuite rendu dans
		// l'email (voir CF_Email), pas supprimé à la sauvegarde.
		update_post_meta( $post_id, '_cfeb_appt_email_message',             wp_kses_post( wp_unslash( $_POST['cfeb_appt_email_message'] ?? '' ) ) );
		update_post_meta( $post_id, '_cfeb_appt_email_message_distanciel',  wp_kses_post( wp_unslash( $_POST['cfeb_appt_email_message_distanciel'] ?? '' ) ) );

		// ── Booking flow ───────────────────────────────────────
		$booking_flow = sanitize_key( wp_unslash( $_POST['cfeb_appt_booking_flow'] ?? 'slot_first' ) );
		if ( ! in_array( $booking_flow, [ 'slot_first', 'form_first' ], true ) ) {
			$booking_flow = 'slot_first';
		}
		update_post_meta( $post_id, '_cfeb_appt_booking_flow', $booking_flow );

		// ── Dates spécifiques ──────────────────────────────────
		$spec_raw   = wp_unslash( $_POST['cfeb_appt_specific_dates'] ?? '' );
		$spec_input = $spec_raw ? json_decode( $spec_raw, true ) : [];
		$spec_clean = [];
		if ( is_array( $spec_input ) ) {
			foreach ( $spec_input as $entry ) {
				$date = sanitize_text_field( $entry['date'] ?? '' );
				if ( ! preg_match( '/^\d{4}-\d{2}-\d{2}$/', $date ) ) {
					continue;
				}
				$slots = [];
				foreach ( (array) ( $entry['slots'] ?? [] ) as $s ) {
					$debut    = sanitize_text_field( $s['debut'] ?? '' );
					$fin      = sanitize_text_field( $s['fin']   ?? '' );
					$modalite = sanitize_key( $s['modalite'] ?? 'presentiel' );
					if ( ! in_array( $modalite, [ 'presentiel', 'distanciel' ], true ) ) {
						$modalite = 'presentiel';
					}
					$lieu_id = sanitize_key( $s['lieu_id'] ?? '' );
					if ( ! in_array( $lieu_id, $valid_lieu_ids, true ) ) {
						$lieu_id = '';
					}
					if ( $debut && $fin && $fin > $debut ) {
						$slots[] = [ 'debut' => $debut, 'fin' => $fin, 'modalite' => $modalite, 'lieu_id' => $lieu_id ];
					}
				}
				if ( ! empty( $slots ) ) {
					$spec_clean[] = [ 'date' => $date, 'slots' => $slots ];
				}
			}
			usort( $spec_clean, function( $a, $b ) { return strcmp( $a['date'], $b['date'] ); } );
		}
		update_post_meta( $post_id, '_cfeb_appt_specific_dates', wp_json_encode( $spec_clean ) );
	}

	/**
	 * Modalité d'un type de RDV : 'presentiel' | 'distanciel' | 'les_deux'.
	 * Repli pour les types déjà existants avant l'ajout de ce champ (jamais
	 * enregistré) : 'distanciel' si une plateforme de réunion en ligne était
	 * déjà configurée, sinon 'presentiel' — reprend le sens implicite que
	 * portait déjà le champ « Plateforme » (option "— Aucune (présentiel) —").
	 */
	public static function get_modalite( $post_id ) {
		$stored = get_post_meta( $post_id, '_cfeb_appt_modalite', true );
		if ( in_array( $stored, [ 'presentiel', 'distanciel', 'les_deux' ], true ) ) {
			return $stored;
		}
		$platform = get_post_meta( $post_id, '_cfeb_appt_online_platform', true );
		return $platform ? 'distanciel' : 'presentiel';
	}

	/* ══════════════════════════════════════════════════════════════
	   LECTURE META
	══════════════════════════════════════════════════════════════ */
	public static function get_meta( $post_id ) {
		$avail_raw = get_post_meta( $post_id, '_cfeb_appt_availability', true );
		$avail     = [];
		if ( $avail_raw ) {
			$decoded = json_decode( $avail_raw, true );
			if ( is_array( $decoded ) ) {
				$avail = $decoded;
			}
		}

		$spec_raw       = get_post_meta( $post_id, '_cfeb_appt_specific_dates', true );
		$specific_dates = [];
		if ( $spec_raw ) {
			$decoded = json_decode( $spec_raw, true );
			if ( is_array( $decoded ) ) {
				$specific_dates = $decoded;
			}
		}

		$cf_raw = get_post_meta( $post_id, '_cfeb_appt_custom_fields', true );
		$cf     = [];
		if ( $cf_raw ) {
			$decoded = json_decode( $cf_raw, true );
			if ( is_array( $decoded ) ) {
				$cf = $decoded;
			}
