	/**
	 * SHORTCODE [cf_rdv_onglets] — plusieurs types de RDV en onglets, au lieu
	 * d'empiler autant de widgets [cf_rdv] les uns sous les autres (page
	 * illisible dès 3-4 types, chacun avec son en-tête et son calendrier).
	 *
	 * Un seul onglet visible à la fois ; tous les widgets sont rendus côté
	 * serveur et simplement masqués, donc changer d'onglet est instantané
	 * (pas d'aller-retour AJAX) et le contenu reste indexable.
	 *
	 * Usage :
	 *   [cf_rdv_onglets type="seance-individuelle, constellations-de-groupes"]
	 *   [cf_rdv_onglets type="seance-individuelle:Séance individuelle, pleine-vie:Soirée de présentation"]
	 *
	 * Le libellé après « : » est facultatif (par défaut, le titre du type).
	 * Chaque onglet reste accessible en lien direct via l'ancre du widget
	 * qu'il contient (#cf-rdv-<slug>) — l'onglet correspondant est
	 * automatiquement sélectionné à l'ouverture (voir frontend.js).
	 */
	public static function shortcode_rdv_onglets( $atts ) {
		$atts = shortcode_atts( [ 'type' => '', 'vue' => '', 'nombre' => 8 ], $atts, 'cf_rdv_onglets' );

		// Pas de type précisé : un onglet par type de RDV publié, dans l'ordre
		// d'affichage habituel (menu_order, puis titre) — usage "zéro config"
		// plutôt qu'un shortcode qui ne rend rien silencieusement.
		if ( ! trim( $atts['type'] ) ) {
			$all_types = get_posts( [
				'post_type'      => CFEB_APPT_SLUG,
				'post_status'    => 'publish',
				'numberposts'    => -1,
				'orderby'        => [ 'menu_order' => 'ASC', 'title' => 'ASC' ],
			] );
			if ( empty( $all_types ) ) {
				return '<p style="color:#b32d2e;">[cf_rdv_onglets] : aucun type de rendez-vous publié n\'a été trouvé. Créez-en un dans CF Réservations → Types RDV, ou précisez l\'attribut type="slug-a, slug-b".</p>';
			}
			$atts['type'] = implode( ',', wp_list_pluck( $all_types, 'post_name' ) );
		}

		// "slug:Libellé, autre-slug" → [ [slug, libellé|null], … ]
		$entries = [];
		foreach ( explode( ',', $atts['type'] ) as $token ) {
			$token = trim( $token );
			if ( '' === $token ) {
				continue;
			}
			$parts = array_map( 'trim', explode( ':', $token, 2 ) );
			$ids   = self::normalize_type_ids( $parts[0] );
			if ( empty( $ids ) ) {
				continue;
			}
			$entries[] = [
				'ids'    => $ids,
				'label'  => ( isset( $parts[1] ) && '' !== $parts[1] ) ? $parts[1] : get_post( $ids[0] )->post_title,
				'anchor' => 'cf-rdv-' . implode( '-', array_map( static function ( $id ) {
					return sanitize_title( get_post( $id )->post_name );
				}, $ids ) ),
			];
		}

		if ( empty( $entries ) ) {
			return current_user_can( 'manage_options' )
				? '<p style="color:#b32d2e;">[cf_rdv_onglets] : aucun des slugs indiqués dans type="' . esc_html( $atts['type'] ) . '" ne correspond à un type de rendez-vous existant.</p>'
				: '';
		}
		// Un seul type utilisable : pas d'onglets, on rend le widget seul.
		if ( 1 === count( $entries ) ) {
			return self::shortcode_rdv( [
				'type'   => implode( ',', $entries[0]['ids'] ),
				'vue'    => $atts['vue'],
				'nombre' => $atts['nombre'],
			] );
		}

		ob_start();
		?>
		<div class="cf-rdv-tabs">
			<div class="cf-rdv-tabs-nav" role="tablist">
				<?php foreach ( $entries as $i => $entry ) : ?>
					<button type="button"
						class="cf-rdv-tab<?php echo 0 === $i ? ' is-active' : ''; ?>"
						role="tab"
						aria-selected="<?php echo 0 === $i ? 'true' : 'false'; ?>"
						data-panel="<?php echo esc_attr( $entry['anchor'] ); ?>"><?php echo esc_html( $entry['label'] ); ?></button>
				<?php endforeach; ?>
			</div>
			<?php foreach ( $entries as $i => $entry ) : ?>
				<div class="cf-rdv-tab-panel<?php echo 0 === $i ? ' is-active' : ''; ?>" data-panel="<?php echo esc_attr( $entry['anchor'] ); ?>" role="tabpanel">
					<?php
					// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
					echo self::shortcode_rdv( [
						'type'   => implode( ',', $entry['ids'] ),
						'vue'    => $atts['vue'],
						'titre'  => 'none', // le libellé de l'onglet fait déjà office de titre
						'nombre' => $atts['nombre'],
					] );
					?>
				</div>
			<?php endforeach; ?>
		</div>
		<?php
		return ob_get_clean();
	}

	public static function shortcode_rdv( $atts ) {
		if ( ! wp_script_is( 'cfeb-frontend', 'enqueued' ) ) {
			wp_enqueue_style(  'cfeb-frontend', CFEB_URL . 'assets/css/frontend.css', [], CFEB_VERSION );
			wp_enqueue_script( 'cfeb-frontend', CFEB_URL . 'assets/js/frontend.js', [], CFEB_VERSION, true );
			wp_localize_script( 'cfeb-frontend', 'cfeb', [
				'ajaxurl' => admin_url( 'admin-ajax.php' ),
				'nonce'   => wp_create_nonce( 'cfeb_front' ),
				'l10n'    => [],
			] );
		}

		$atts = shortcode_atts( [ 'type' => '', 'vue' => '', 'titre' => '', 'nombre' => 8 ], $atts, 'cf_rdv' );
		$nombre_liste = min( 50, max( 1, absint( $atts['nombre'] ) ) );
		if ( ! $atts['type'] ) {
			return '';
		}

		// Un ou plusieurs types : type="a", type="a,b" ou type="a + b".
		$type_ids = self::normalize_type_ids( $atts['type'] );
		if ( empty( $type_ids ) ) {
			return '';
		}
		$type_post = get_post( $type_ids[0] ); // type principal : gabarit, instructions…
		$multi     = count( $type_ids ) > 1;

		// Ancre stable pour lien direct (ex. depuis un email MailPoet) :
		// /prendre-rdv/#cf-rdv-<slug-du-type>. Basée sur le(s) slug(s) des
		// types affichés par ce widget.
		$anchor_id = 'cf-rdv-' . implode( '-', array_map( static function ( $id ) {
			return sanitize_title( get_post( $id )->post_name );
		}, $type_ids ) );

		// Shortcode attribute overrides, otherwise use the layout saved on the (first) type
		$m      = self::get_meta( $type_post->ID );
		$layout = $m['layout'] ?: 'hebdomadaire'; // hebdomadaire | mensuel | liste
		if ( $atts['vue'] && in_array( $atts['vue'], [ 'semaine', 'liste' ], true ) ) {
			$vue = $atts['vue'];
		} else {
			$vue = ( 'liste' === $layout ) ? 'liste' : 'semaine';
		}

		// Titre : personnalisable via l'attribut `titre` (titre="none" pour le masquer).
		// Par défaut, on concatène les titres des types affichés.
		if ( 'none' === strtolower( trim( $atts['titre'] ) ) ) {
			$titre = '';
		} elseif ( '' !== trim( $atts['titre'] ) ) {
			$titre = $atts['titre'];
		} elseif ( $multi ) {
			$titre = implode( ' · ', array_map( static function ( $id ) {
				return get_post( $id )->post_title;
			}, $type_ids ) );
		} else {
			$titre = $type_post->post_title;
		}

		// Le réglage global (Réglages → Téléphone obligatoire) ne s'applique
		// qu'au widget événements historique ([cf_events]/venue) : chaque
		// type de rendez-vous a sa propre case « Téléphone obligatoire »
		// dans sa fiche « Informations client », qui fait autorité ici (et
		// peut donc bien désactiver l'obligation même si le réglage global
		// est coché).
		$tel_requis = false;
		foreach ( $type_ids as $tid ) {
			if ( self::get_meta( $tid )['require_phone'] ) {
				$tel_requis = true;
				break;
			}
		}

		// Lundi de la semaine courante
		$today    = strtotime( 'today' );
		$dow      = (int) date( 'N', $today );
		$week_mon = date( 'Y-m-d', $today - ( $dow - 1 ) * DAY_IN_SECONDS );

		ob_start();
		?>
		<div id="<?php echo esc_attr( $anchor_id ); ?>" class="cf-rdv-widget" data-type-id="<?php echo esc_attr( implode( ',', $type_ids ) ); ?>">
			<?php if ( '' !== $titre ) : ?>
				<h3 class="cf-rdv-title"><?php echo esc_html( $titre ); ?></h3>
			<?php endif; ?>
			<?php if ( ! $multi && $m['instructions'] ) : ?>
				<p class="cf-rdv-instructions"><?php echo esc_html( $m['instructions'] ); ?></p>
			<?php endif; ?>

			<?php if ( 'liste' === $vue ) : ?>
			<div class="cf-rdv-list-wrap">
				<?php
				// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
				echo self::render_slot_list( $type_ids, null, $nombre_liste );
				?>
			</div>
		<?php else : ?>
			<div class="cf-rdv-cal">
				<div class="cf-rdv-cal-body">
					<?php
					// phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped
					echo self::render_week_grid( $type_ids, $week_mon );
					?>
				</div>
				<div class="cf-rdv-cal-loading" style="display:none;"><span>Chargement…</span></div>
			</div>
		<?php endif; ?>

			<!-- Formulaire de réservation (masqué par défaut) -->
			<div class="cf-rdv-form-container" style="display:none;">
				<h4 class="cf-rdv-form-slot-title"></h4>
				<form class="cf-rdv-form">
					<input type="hidden" name="action"       value="cfeb_reserver" />
					<input type="hidden" name="nonce"        value="<?php echo esc_attr( wp_create_nonce( 'cfeb_front' ) ); ?>" />
					<input type="hidden" name="event_id"     value="0" class="cf-rdv-event-id" />
					<input type="hidden" name="slot_debut"   value="" class="cf-rdv-slot-debut" />
					<input type="hidden" name="slot_fin"     value="" class="cf-rdv-slot-fin" />
					<input type="hidden" name="appt_type_id" value="<?php echo (int) $type_post->ID; ?>" />
					<div class="cf-rdv-form-grid">
						<div class="cf-rdv-field">
							<label>Prénom *</label>
							<input type="text" name="prenom" required class="cf-field-input" />
						</div>
